# --- framebuffer ---------------------------------------------------------

def new_canvas():
    buf = bytearray(W * H * 3)
    r, g, b = BG
    for i in range(0, len(buf), 3):
        buf[i] = r
        buf[i + 1] = g
        buf[i + 2] = b
    return buf


def rect(buf, x, y, w, h, color):
    if w <= 0 or h <= 0:
        return
    x0 = max(0, x)
    y0 = max(0, y)
    x1 = min(W, x + w)
    y1 = min(H, y + h)
    if x0 >= x1 or y0 >= y1:
        return
    row = bytes(color) * (x1 - x0)
    for yy in range(y0, y1):
        off = (yy * W + x0) * 3
        buf[off:off + len(row)] = row


def hline(buf, x0, x1, y, color, width=2):
    rect(buf, x0, y, x1 - x0, width, color)


# --- bitmap text ---------------------------------------------------------

def text_width(text, font, scale):
    w = 0
    for ch in text:
        g = font.get(ch) or font[" "]
        w += (g[0] + 1) * scale
    return max(0, w - scale)


def draw_text(buf, text, x, baseline_y, font, scale, color):
    cx = x
    for ch in text:
        g = font.get(ch) or font[" "]
        w, top, rows = g
        gy = baseline_y + top * scale
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit == "#":
                    rect(buf, cx + rx * scale, gy + ry * scale,
                         scale, scale, color)
        cx += (w + 1) * scale
    return cx


def draw_text_centered(buf, text, cx, baseline_y, font, scale, color):
    draw_text(buf, text, cx - text_width(text, font, scale) // 2,
              baseline_y, font, scale, color)


def wrap(text, font, scale, width):
    words, lines, cur = text.split(), [], ""
    for w in words:
        t = (cur + " " + w).strip()
        if text_width(t, font, scale) <= width:
            cur = t
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


# --- PNG encoder (stdlib only) -------------------------------------------

def chunk(typ, data):
    out = struct.pack(">I", len(data)) + typ + data
    out += struct.pack(">I", crc32(typ + data) & 0xFFFFFFFF)
    return out


def save_png(buf, path):
    raw = b"".join(
        b"\x00" + bytes(buf[y * W * 3:(y + 1) * W * 3])
        for y in range(H)
    )
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


